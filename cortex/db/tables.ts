/**
 * SOURCE DE VÉRITÉ du schéma applicatif — Phase B backend-overhaul.
 *
 * Historiquement le schéma vivait en 3 endroits divergents : db/schema.ts
 * (Drizzle, 6 tables), db/migrations/0000_*.sql (les mêmes 6) et ~15 tables
 * « lazy » (CREATE TABLE IF NOT EXISTS + ALTER au fil de l'eau dans lib/*).
 * Ce module unifie TOUT en une spec neutre, et génère le DDL des deux dialectes :
 *  - SQLite : identique octet pour octet aux formes historiques fusionnées
 *    (défauts datetime('now'), AUTOINCREMENT…) — appliqué en IF NOT EXISTS,
 *    donc no-op sur les DB existantes (règle d'or : le schéma de cs-202 n'est
 *    jamais modifié au démarrage ; les ensures restent LAZY, aux mêmes points).
 *  - Postgres : types équivalents (integer identity, double precision) avec
 *    timestamps TEXT au MÊME format UTC que SQLite ('YYYY-MM-DD HH24:MI:SS')
 *    et JSON en TEXT — choix délibéré : parité de comportement avec le SQL brut
 *    existant AVANT optimisation PG-native (jsonb/timestamptz viendront après).
 *
 * `GENERATED BY DEFAULT AS IDENTITY` (pas ALWAYS) : la migration SQLite→PG
 * importe les ids historiques tels quels, puis restaure la séquence.
 */

export type ColType = "int" | "real" | "text";

export type Col = {
  name: string;
  type: ColType;
  pk?: boolean;
  /** AUTOINCREMENT (implique pk int). */
  ai?: boolean;
  nn?: boolean;
  /** Défaut : nombre, chaîne SQL déjà quotée, ou "NOW" (timestamp courant UTC). */
  def?: number | string;
  unique?: boolean;
  fk?: { table: string; col: string; onDelete?: "cascade" };
};

export type TableSpec = {
  name: string;
  cols: Col[];
  uniqueIndexes?: { name: string; cols: string[] }[];
};

