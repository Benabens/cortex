export type Dialect = "sqlite" | "postgres";

const PG_NOW_DEFAULT = "to_char((now() AT TIME ZONE 'utc'), 'YYYY-MM-DD HH24:MI:SS')";

function colType(c: Col, dialect: Dialect): string {
  if (dialect === "sqlite") return c.type === "int" ? "INTEGER" : c.type === "real" ? "REAL" : "TEXT";
  return c.type === "int" ? "integer" : c.type === "real" ? "double precision" : "text";
}

function colDdl(c: Col, dialect: Dialect): string {
  const parts: string[] = [c.name, colType(c, dialect)];
  if (c.pk) {
    if (c.ai) {
      parts.push(dialect === "sqlite" ? "PRIMARY KEY AUTOINCREMENT" : "GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY");
    } else {
      parts.push("PRIMARY KEY");
    }
  }
  if (c.nn && !c.pk) parts.push("NOT NULL");
  if (c.def !== undefined) {
    const def = c.def === "NOW" ? (dialect === "sqlite" ? "(datetime('now'))" : `(${PG_NOW_DEFAULT})`) : String(c.def);
    parts.push(`DEFAULT ${def}`);
  }
  if (c.unique) parts.push("UNIQUE");
  return parts.join(" ");
}

/** DDL idempotent (CREATE TABLE IF NOT EXISTS + index uniques) d'une table. */
export function tableDdl(spec: TableSpec, dialect: Dialect): string[] {
  const cols = spec.cols.map((c) => colDdl(c, dialect));
  const fks = spec.cols
    .filter((c) => c.fk)
    .map((c) => `FOREIGN KEY (${c.name}) REFERENCES ${c.fk!.table}(${c.fk!.col})${c.fk!.onDelete === "cascade" ? " ON DELETE CASCADE" : ""}`);
  const stmts = [`CREATE TABLE IF NOT EXISTS ${spec.name} (\n  ${[...cols, ...fks].join(",\n  ")}\n)`];
  for (const idx of spec.uniqueIndexes ?? []) {
    stmts.push(`CREATE UNIQUE INDEX IF NOT EXISTS ${idx.name} ON ${spec.name} (${idx.cols.join(", ")})`);
  }
  return stmts;
}

export function getTable(name: string): TableSpec {
  const t = TABLES.find((t) => t.name === name);
  if (!t) throw new Error(`Table inconnue dans db/tables.ts : ${name}`);
  return t;
}

/** DDL d'une table nommée (raccourci des ensures lazy). */
export function ddl(name: string, dialect: Dialect): string[] {
  return tableDdl(getTable(name), dialect);
}

/** DDL complet du schéma applicatif (ordre = TABLES, respecte les FK). */
export function allDdl(dialect: Dialect): string[] {
  return TABLES.flatMap((t) => tableDdl(t, dialect));
}
